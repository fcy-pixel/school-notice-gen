/**
 * Creates src/general-template-b64.js by transforming the activity template:
 *  - Replaces {{活動名稱}} with {{標題}} in the header table
 *  - Replaces the activity body (敬啟者…contact paragraphs) with
 *    {{收件人}}，  /  {{正文}}
 *  - Replaces ＜{{學年}}年度{{通告編號}}回條＞ with {{回條標題}} in the reply header
 *  - Replaces the activity-specific reply items with {{回條項目}} + signature lines
 */
import { TEMPLATE_B64 } from '../src/template-b64.js';
import JSZip from 'jszip';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const RF = 'w:asciiTheme="majorEastAsia" w:eastAsiaTheme="majorEastAsia" w:hAnsiTheme="majorEastAsia"';
const CS_HK = 'w:cs="華康香港標準楷書"';

/** Build a simple run XML with optional underline */
function run(text, { underline = false, hint = 'eastAsia' } = {}) {
  const uTag = underline ? '<w:u w:val="single"/>' : '';
  const hintAttr = hint ? ` w:hint="${hint}"` : '';
  return `<w:r><w:rPr><w:rFonts ${RF} ${CS_HK}${hintAttr}/>${uTag}</w:rPr><w:t xml:space="preserve">${text}</w:t></w:r>`;
}

/** Build a paragraph XML with given content and optional formatting */
function para(inner, { spacing = 320, indent = null, jc = null } = {}) {
  const indTag = indent ? `<w:ind ${indent}/>` : '';
  const jcTag = jc ? `<w:jc w:val="${jc}"/>` : '';
  return `<w:p><w:pPr><w:snapToGrid w:val="0"/><w:spacing w:line="${spacing}" w:lineRule="exact"/>${indTag}${jcTag}<w:rPr><w:rFonts ${RF} ${CS_HK}/></w:rPr></w:pPr>${inner}</w:p>`;
}

async function main() {
  // Decode activity template
  const bin = atob(TEMPLATE_B64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const zip = await JSZip.loadAsync(bytes.buffer);
  let doc = await zip.file('word/document.xml').async('string');

  // ─── 1. Header table: rename 活動名稱 → 標題 ────────────────────────────────
  doc = doc.replace('<w:t>{{活動名稱}}</w:t>', '<w:t>{{標題}}</w:t>');

  // ─── 2. Body section: replace from 敬啟者 → before 此致 ─────────────────────
  const BODY_START_MARKER = '<w:t>敬啟者：</w:t>';
  const BODY_END_MARKER = '<w:t xml:space="preserve">　　  此致</w:t>';

  const bodyStartIdx = doc.indexOf(BODY_START_MARKER);
  const bodyEndIdx = doc.indexOf(BODY_END_MARKER);
  if (bodyStartIdx === -1) throw new Error('Cannot find 敬啟者');
  if (bodyEndIdx === -1) throw new Error('Cannot find 此致');

  const paraBeforeBody = doc.lastIndexOf('<w:p ', bodyStartIdx);
  const paraBeforeEnd = doc.lastIndexOf('<w:p ', bodyEndIdx);

  // New body: recipient line, blank, body text (multiline-expanded by fillTemplate)
  const newBody = [
    para(run('{{收件人}}，'), { jc: 'both' }),
    para('', {}),
    para(run('{{正文}}'), { indent: 'w:firstLineChars="200" w:firstLine="480"', jc: 'both' }),
    para('', {}),
  ].join('');

  doc = doc.slice(0, paraBeforeBody) + newBody + doc.slice(paraBeforeEnd);

  // ─── 3. Reply slip header: ＜{{學年}}…回條＞ → {{回條標題}} ──────────────────
  doc = doc.replace(
    '<w:t>＜{{學年}}年度{{通告編號}}回條＞</w:t>',
    '<w:t>{{回條標題}}</w:t>',
  );

  // ─── 4. Reply slip body: remove activity items, add {{回條項目}} + signature ─
  const REPLY_ITEM_MARKER = '本人已知悉 貴校通告';
  const replyItemIdx = doc.indexOf(REPLY_ITEM_MARKER);
  if (replyItemIdx === -1) throw new Error('Cannot find reply item marker');

  const replyParaStart = doc.lastIndexOf('<w:p ', replyItemIdx);
  const sectPrIdx = doc.lastIndexOf('<w:sectPr');
  const lastParaEnd = doc.lastIndexOf('</w:p>', sectPrIdx) + '</w:p>'.length;

  // Reply items ({{回條項目}} will be multi-line expanded) + blank + signature line
  const newReply = [
    para(run('{{回條項目}}'), { jc: 'both' }),
    para('', {}),
    // Signature line: 年級___班  學生姓名___  家長簽署___
    `<w:p><w:pPr><w:snapToGrid w:val="0"/><w:spacing w:line="320" w:lineRule="exact"/><w:rPr><w:rFonts ${RF} ${CS_HK}/></w:rPr></w:pPr>` +
      run('　　年級') +
      run('　　　', { underline: true }) +
      run('班　　學生姓名') +
      run('　　　　　　　　', { underline: true }) +
      `</w:p>`,
    `<w:p><w:pPr><w:snapToGrid w:val="0"/><w:spacing w:line="320" w:lineRule="exact"/><w:rPr><w:rFonts ${RF} ${CS_HK}/></w:rPr></w:pPr>` +
      run('　　家長簽署') +
      run('　　　　　　　　　　', { underline: true }) +
      `</w:p>`,
    para('', {}),
  ].join('');

  doc = doc.slice(0, replyParaStart) + newReply + doc.slice(lastParaEnd);

  // ─── Save modified document ───────────────────────────────────────────────────
  zip.file('word/document.xml', doc);
  const newBytes = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
  const b64 = newBytes.toString('base64');

  const outPath = path.join(__dirname, '../src/general-template-b64.js');
  fs.writeFileSync(
    outPath,
    `// Auto-generated by scripts/make-general-template.mjs — DO NOT EDIT MANUALLY\nexport const GENERAL_TEMPLATE_B64 = '${b64}';\n`,
  );

  console.log(`✓ Written ${newBytes.length} bytes → src/general-template-b64.js`);

  // Quick sanity check: verify key placeholders are still present
  const check = ['{{標題}}', '{{收件人}}', '{{正文}}', '{{回條標題}}', '{{回條項目}}', '{{回條截止日期}}', '{{學年}}', '{{通告編號}}', '{{發出日期}}'];
  for (const ph of check) {
    if (!doc.includes(ph)) console.warn(`  ⚠  Missing placeholder: ${ph}`);
    else console.log(`  ✓  ${ph}`);
  }
}

main().catch(e => { console.error(e); process.exit(1); });
